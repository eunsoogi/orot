const { readFileSync, writeFileSync } = require('node:fs') as {
  readFileSync(path: string, encoding: 'utf8'): string;
  writeFileSync(path: string, content: string): void;
};
const { join, resolve } = require('node:path') as {
  join(...parts: string[]): string;
  resolve(...parts: string[]): string;
};
declare const __dirname: string;
import type { SavedPeriodSummarySource } from '../../diseaseHypotheses/savedSummaries';
import { reference } from '../../diseaseHypotheses/taskTestSupport';
import { assertPeriodNotRemoved } from '../conversationPeriodRemoval';

/** Keep the native exact allowlist in sync with static source SQL, never bindings
 * or user data. Runtime mismatches fall back to normal execution, not stale results. */
test('native candidate manifest covers all sixteen exact period-removal templates', async () => {
  const queries = new Set<string>();
  for (const topic of [
    'measurements',
    'activity',
    'sleep',
    'symptoms',
    'medications',
  ] as const) {
    const source: SavedPeriodSummarySource = {
      kind: 'health_context_period',
      reference,
      revision: 'synthetic',
      deletionGeneration: 0,
      scope: {
        kind: 'health_context_period',
        version: 1,
        topic,
        window: {
          fromInclusive: '2026-10-01T00:00:00Z',
          toExclusive: '2026-10-05T00:00:00Z',
          timeZone: 'UTC',
        },
      },
    };
    await assertPeriodNotRemoved(
      {
        execute: async (sql, bindings) => {
          expect(bindings).toHaveLength(3);
          queries.add(sql);
          return { rows: [] };
        },
      },
      source,
    );
  }
  expect(queries.size).toBe(16);
  for (const sql of queries) {
    expect(sql.startsWith('SELECT id FROM (')).toBe(true);
    expect(sql.endsWith(') LIMIT 1')).toBe(true);
  }
  const patch = readFileSync(
    resolve(
      __dirname,
      '../../../../../vendor/patches/@op-engineering__op-sqlite@18.2.5.patch',
    ),
    'utf8',
  );
  const nativeQueries = patch
    .split('\n')
    .filter(line => line.startsWith('+"SELECT id FROM ('))
    .map(line => JSON.parse(line.slice(1).replace(/,$/, '')) as string);
  expect(nativeQueries.sort()).toEqual([...queries].sort());
  const output = (
    jest.requireActual('node:process').env as Record<string, string | undefined>
  ).OROT_NATIVE_MANIFEST_DIR;
  if (output) {
    const values = [...queries].sort();
    writeFileSync(
      join(output, 'OrotPeriodQueries.hpp'),
      '#pragma once\n#include <string>\n#include <string_view>\nnamespace opsqlite {\n' +
        '// Generated from the sixteen static period removal queries. No user inputs.\n' +
        'inline bool orotCacheEligible(const std::string& sql) {\n' +
        '  static constexpr std::string_view queries[] = {\n' +
        values.map(sql => JSON.stringify(sql) + ',').join('\n') +
        '\n  };\n  for (const auto query : queries) if (query == sql) return true;\n' +
        '  return false;\n}\n} // namespace opsqlite\n',
    );
    writeFileSync(
      join(output, 'PeriodRemovalAllowlist.hpp'),
      '#pragma once\n#include <string>\n#include <unordered_set>\n' +
        '// Generated by periodRemovalNativeManifest.test.ts from static source SQL only.\n' +
        'inline const std::unordered_set<std::string> periodRemovalAllowlist = {\n' +
        values.map(sql => JSON.stringify(sql) + ',').join('\n') +
        '\n};\n',
    );
  }
});
